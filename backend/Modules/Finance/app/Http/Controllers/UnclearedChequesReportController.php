<?php

declare(strict_types=1);

namespace Modules\Finance\Http\Controllers;

use Barryvdh\DomPDF\Facade\Pdf;
use Carbon\CarbonImmutable;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Response;
use Illuminate\Routing\Controller;
use Modules\Finance\Http\Requests\UnclearedChequesReportRequest;
use Modules\Finance\Services\UnclearedChequesReportService;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Uncleared Cheques report: screen, PDF and CSV from one build, so the three
 * always agree. Open to anyone who reconciles banks or reads finance reports;
 * the service limits it to the user's companies.
 */
class UnclearedChequesReportController extends Controller
{
    public function __construct(private readonly UnclearedChequesReportService $service)
    {
        $this->middleware('permission:view_bank_reconciliations|view_finance_reports');
    }

    public function options(): JsonResponse
    {
        return response()->json(['data' => [
            'companies'     => $this->service->companyOptions(),
            'bank_accounts' => $this->service->bankAccountOptions(),
        ]]);
    }

    public function index(UnclearedChequesReportRequest $request): JsonResponse
    {
        return response()->json(['data' => $this->service->build($request->filters())]);
    }

    public function pdf(UnclearedChequesReportRequest $request): Response
    {
        $data = $this->service->build($request->filters());

        return Pdf::loadView('finance::pdf.uncleared_cheques', $data)
            ->setPaper('a4', 'landscape')
            ->setOptions([
                'defaultFont'          => 'DejaVu Sans',
                'isHtml5ParserEnabled' => true,
                'isPhpEnabled'         => false,
                'dpi'                  => 150,
            ])
            ->download($this->filename($data['header']['as_at'], 'pdf'));
    }

    public function csv(UnclearedChequesReportRequest $request): StreamedResponse
    {
        $data = $this->service->build($request->filters());

        return response()->streamDownload(function () use ($data): void {
            $out    = fopen('php://output', 'w');
            $header = $data['header'];

            fwrite($out, "\xEF\xBB\xBF"); // so Excel reads UTF-8 names correctly
            $this->row($out, ['Uncleared Cheques']);
            $this->row($out, [$header['company_name'], $header['company_address']]);
            $this->row($out, ['As at', $header['as_at'], 'Bank Account', $header['bank_account'], 'Type', $header['type_label']]);
            $this->row($out, ['Generated By', $header['generated_by'], 'Generated Time', $header['generated_at']]);
            $this->row($out, []);
            $this->row($out, [
                'Bank Account', 'Type', 'Cheque No', 'Cheque Date', 'Journal No', 'Journal Date', 'Document No',
                'Party', 'Drawee Bank', 'Description', 'Days Outstanding', 'Flags', 'Amount',
            ]);

            foreach ($data['rows'] as $r) {
                $this->row($out, [
                    $r['bank_account'],
                    $r['type'] === UnclearedChequesReportService::TYPE_ISSUED ? 'Issued' : 'Deposited',
                    $r['cheque_no'],
                    $r['cheque_date'],
                    $r['journal_no'],
                    $r['journal_date'],
                    $r['document_no'],
                    $r['party_name'],
                    $r['drawee_bank'],
                    $r['description'],
                    $r['days_outstanding'],
                    implode(' ', array_filter([$r['is_stale'] ? 'Stale' : null, $r['is_post_dated'] ? 'Post-dated' : null])),
                    $r['amount'],
                ]);
            }

            $s = $data['summary'];
            $this->row($out, []);
            $this->row($out, ['Issued, not presented', $s['issued_count'] . ' cheque(s)', $s['issued_total']]);
            $this->row($out, ['Deposited, not cleared', $s['received_count'] . ' cheque(s)', $s['received_total']]);

            if ($data['truncated']) {
                $this->row($out, ['Only the first ' . UnclearedChequesReportService::MAX_ROWS . ' cheques are listed. Narrow the filters.']);
            }

            fclose($out);
        }, $this->filename($data['header']['as_at'], 'csv'), [
            'Content-Type' => 'text/csv; charset=UTF-8',
        ]);
    }

    /**
     * One CSV row. A cell that starts with = + - @ is prefixed with a quote,
     * so a party or description typed as a formula never runs in Excel.
     *
     * @param resource          $out
     * @param list<scalar|null> $cells
     */
    private function row($out, array $cells): void
    {
        fputcsv($out, array_map(function ($v) {
            if (is_string($v) && $v !== '' && ! is_numeric($v) && in_array($v[0], ['=', '+', '-', '@', "\t", "\r"], true)) {
                return "'" . $v;
            }

            return $v;
        }, $cells));
    }

    private function filename(string $asAt, string $extension): string
    {
        return 'UnclearedCheques_' . CarbonImmutable::parse($asAt)->format('Ymd') . '.' . $extension;
    }
}
